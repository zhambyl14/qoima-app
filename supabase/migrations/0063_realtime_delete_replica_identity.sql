--  0063 · Клиенттің мекенжайды өшіру батырмасы жұмыс істемейтін баг түзетуі
-- ────────────────────────────────────────────────────────────────────────────
--  Себебі: .stream(primaryKey: ['id']).eq('client_uid', uid) клиент жағында
--  DELETE оқиғасын client_uid бойынша сүзеді. Бірақ REPLICA IDENTITY әдепкі
--  бойынша тек PRIMARY KEY бағанын (id) жібереді — client_uid жоқ болғандықтан
--  supabase-flutter сүзгіге сәйкестендіре алмай, оқиғаны ЖОЯДЫ (silently
--  drop). Нәтижесінде DELETE серверде СӘТТІ орындалады, бірақ тізім экраннан
--  жоғалмайды — клиентке «өшірілмеді» болып көрінеді.
--
--  Түзету: REPLICA IDENTITY FULL — DELETE оқиғасына БАРЛЫҚ бағанды қосады,
--  сүзгі client_uid-ті таба алады да, жол ағыннан дұрыс жойылады.
--
--  favorites да дәл сол үлгі (client_uid бойынша сүзілетін .stream() + delete)
--  — сол баг сонда да бар, алдын алу үшін бірге түзетілді.
-- ════════════════════════════════════════════════════════════════════════════

alter table public.addresses replica identity full;
alter table public.favorites replica identity full;
