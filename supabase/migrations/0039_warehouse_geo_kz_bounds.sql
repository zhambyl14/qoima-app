--  БАГ: ескі (бұзылған) Yandex веб-картасы карта жүктелмеген күйде де түртуді
--  қабылдап, қоқыс координат сақтап қоятын — тірі базада «Alash» қоймасы
--  lat=-29.52 / lng=-159.49 (Тынық мұхит) болып тұрған. Клиент картасында ол
--  дүкен мұхиттың ортасында белгі ретінде шығады.
--
--  Түзету: ҚР шекарасынан тыс координаттарды NULL-ге қайтарамыз (админ қайта
--  белгілейді — «белгіленбеген» дұрыс күй) және CHECK шектеуімен бұдан былай
--  мұндай жазбаның сақталуын бұғаттаймыз (қосымша жағында да тексеріледі:
--  warehouse_map_picker_screen.dart — дүкен қаласының радиусы).
-- ════════════════════════════════════════════════════════════════════════════

-- ── 1) Қате координаттарды тазалау ───────────────────────────────────────────
update public.warehouses
   set lat = null, lng = null
 where (lat is not null or lng is not null)
   and (lat is null or lng is null
        or lat < 40.5 or lat > 55.6
        or lng < 46.2 or lng > 87.5);

-- ── 2) Бұдан былай ҚР-дан тыс координат сақталмасын ──────────────────────────
alter table public.warehouses
  drop constraint if exists warehouses_geo_within_kz;

alter table public.warehouses
  add constraint warehouses_geo_within_kz check (
    (lat is null and lng is null)
    or (lat between 40.5 and 55.6 and lng between 46.2 and 87.5)
  );
