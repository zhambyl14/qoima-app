/// type (канондық орысша) → ол кіретін санат кілттері.
export const TYPE_CATEGORIES: Map<string, string[]> = (() => {
  const m = new Map<string, string[]>();
  for (const line of CATALOG_TEXT.split("\n")) {
    const key = line.split(" ")[0];
    const types = line.slice(line.indexOf(":") + 1).split(",").map((t) => t.trim());
    for (const t of types) m.set(t, [...(m.get(t) ?? []), key]);
  }
  return m;
})();
