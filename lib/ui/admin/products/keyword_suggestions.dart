/// «Ұқсас сөздер» (0062) үшін ЖЕРГІЛІКТІ, лезде ұсыныс: желі де, AI да керек емес.
///
/// Клиент тауарды атауымен емес, өз сөзімен іздейді: «сникерс», «кросы»,
/// «спорттық аяқ киім», «найк». Дүкен иесі мұны өзі ойлап таппайды — сондықтан
/// түр/категория/бренд/түс/маусым/кімге бойынша дайын сөздер ұсынамыз.
///
/// Тазы функция (Flutter-сіз): тесттеледі. Канондық мәндер (түр, түс, маусым,
/// кімге) — DB-дегі орысша жолдар, [kTypesByCategory] сияқты.
library;

import '../../../core/search_helper.dart';

/// Іздеу буферінде сөздер ", " арқылы бөлінеді (client_service.dart —
/// SearchHelper бос орын/үтір бойынша сөз іздейді, формат бұрынғыдай қалады).
const String kKeywordSeparator = ', ';

/// Өрістегі мәтінді таза сөздер тізіміне бөледі (үтір / нүктелі үтір / жаңа жол).
List<String> parseKeywordList(String raw) {
  final seen = <String>{};
  final out = <String>[];
  for (final part in raw.split(RegExp(r'[,;\n]'))) {
    final w = part.trim();
    if (w.isEmpty) continue;
    if (seen.add(w.toLowerCase())) out.add(w);
  }
  return out;
}

/// Бар мәтінге жаңа сөздерді қосады (қайталанбайды, регистрге тәуелсіз).
/// Нәтиже — өрісте сақталатын формат: «a, b, c».
String mergeKeywords(String existing, Iterable<String> add) {
  final list = parseKeywordList(existing);
  final seen = {for (final w in list) w.toLowerCase()};
  for (final raw in add) {
    final w = raw.trim();
    if (w.isEmpty) continue;
    if (seen.add(w.toLowerCase())) list.add(w);
  }
  return list.join(kKeywordSeparator);
}

/// Өрістен бір сөзді алып тастау.
String removeKeyword(String existing, String word) {
  final key = word.trim().toLowerCase();
  return parseKeywordList(existing)
      .where((w) => w.toLowerCase() != key)
      .join(kKeywordSeparator);
}

/// Ұсыныстар тізімі (жоғарыдан төмен — маңыздылығы бойынша, ең көбі [max]).
///
/// Атаудағы сөздер, өрісте бар сөздер және [alsoKnown] (тауардың өзінде бар,
/// іздеу буферіне бәрібір түсетін мәндер — түр/түс аты) ұсынылмайды.
List<String> suggestKeywords({
  required String name,
  String brand = '',
  String? categoryKey,
  String? type,
  String? audience,
  Iterable<String> colors = const [],
  Iterable<String> seasons = const [],
  Iterable<String> existing = const [],
  Iterable<String> alsoKnown = const [],
  int max = 12,
}) {
  // Топтар: әрқайсысынан кезекпен бір-бірден аламыз, сонда тізім бір-ақ
  // түрдің синонимдерімен толып кетпейді (тип → категория → бренд → ...).
  final groups = <List<String>>[
    if (type != null) _typeWords[type] ?? const <String>[],
    if (categoryKey != null) _categoryWords[categoryKey] ?? const <String>[],
    _brandForms(brand),
    if (audience != null) _audienceWords[audience] ?? const <String>[],
    for (final c in colors) _colorWords[c] ?? const <String>[],
    for (final s in seasons) _seasonWords[s] ?? const <String>[],
  ];

  final blockedNorm = <String>{
    for (final w in existing) SearchHelper.normalize(w),
    for (final w in alsoKnown) SearchHelper.normalize(w),
  };
  final nameNorm = SearchHelper.normalize(name);
  final nameTokens = nameNorm
      .split(RegExp(r'[^a-z0-9]+'))
      .where((t) => t.isNotEmpty)
      .toSet();

  bool allowed(String w) {
    final n = SearchHelper.normalize(w);
    if (n.length < 2) return false;
    if (blockedNorm.contains(n)) return false;
    if (nameTokens.contains(n)) return false;
    // Атаудың ішінде тұтас тіркес болып тұрса да керек емес.
    if (n.contains(' ') && nameNorm.contains(n)) return false;
    return true;
  }

  final out = <String>[];
  final seen = <String>{};
  final cursor = List<int>.filled(groups.length, 0);
  var progressed = true;
  while (out.length < max && progressed) {
    progressed = false;
    for (var gi = 0; gi < groups.length && out.length < max; gi++) {
      final g = groups[gi];
      while (cursor[gi] < g.length) {
        final w = g[cursor[gi]++];
        if (!allowed(w)) continue;
        if (!seen.add(SearchHelper.normalize(w))) continue;
        out.add(w);
        progressed = true;
        break;
      }
    }
  }
  return out;
}

/// Бренд: жазылуы + кириллица/латын баламасы («Nike» → «найк»).
List<String> _brandForms(String brand) {
  final b = brand.trim().toLowerCase();
  if (b.isEmpty) return const [];
  for (final forms in _brandAliases) {
    if (forms.contains(b)) {
      return [for (final f in forms) if (f != b) f];
    }
  }
  return const [];
}

